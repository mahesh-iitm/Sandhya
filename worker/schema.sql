CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,lat REAL,lng REAL,el REAL,place TEXT,tz TEXT,prefs TEXT,sub TEXT,next_at INTEGER,next_k TEXT,last_push INTEGER,last_status INTEGER,updated INTEGER);
CREATE INDEX IF NOT EXISTS users_next ON users(next_at) WHERE sub IS NOT NULL;
CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY,v TEXT);
